                            <p style="text-align: justify;">Ada beberapa komponen yang harus diperhatikan saat akan mendirikan suatu bangunan, salah satunya adalah atap. Pemilihan atap harus dilakukan dengan benar karena elemen ini memiliki peran yang sangat penting, di antaranya untuk melindungi penghuni bangunan dari teriknya sinar matahari, sinar ultraviolet, hujan, angin serta debu yang bertebaran. Jenis atap sendiri ada beberapa macam, seperti atap yang terbuat dari genteng tanah liat, metal, asbes, hingga atap UPVC.</p>
