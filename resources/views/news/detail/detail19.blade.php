                            <p style="text-align: justify;">Kain spunbond Amari sangat cocok digunakan sebagai pelindung tanaman karena memiliki karakteristik lembaran yang ringan namun memberikan proteksi sempurna, sehingga bahan ini mudah untuk diaplikasikan untuk menutup tanaman. Temperatur di dalam selubung spunbond lebih hangat daripada suhu udara luar sehingga hal ini membuat panas dan kelembaban lebih terkontrol dan dapat meningkatkan kualitas hasil panen. Perlindungan kain spunbond dapat mengatur sirkulasi udara dan jumlah sinar matahari yang mengenai tanaman sehingga dapat memperlancar proses fotosintesis namun tanaman tetap terlindung dari bahaya sinar UV yang berlebih. Tanaman yang biasa menggunakan metode perlindungan ini contohnya adalah melon, semangka, tomat dan mentimun.</p>
                            <p style="text-align: justify;">Di ladang atau perkebunan, kain spunbond banyak digunakan untuk membungkus buah yang belum matang, seperti pada pohon pisang. Hal ini membuat buah-buahan lebih terlindung dari hama dan serangga serta wabah yang dibawa oleh serangga. Pembungkus buah dari kain spunbond ini dapat melindungi buah secara individu misalnya buah pepaya, maupun jenis buah yang berkerumun seperti pisang. Dengan metode perlindungan ini, pertumbuhan buah akan lebih baik, lebih sehat dan dapat menghasilkan buah yang lebih berkualitas serta mempercepat masa panen.</p>
                            <p style="text-align: justify;">Spunbond juga dapat digunakan untukwadah bibit tanaman yang baru ditanam. Dibandingkan dengan kantong plastik, kantong yang terbuat dari spunbond memiliki daya serap air dan udara yang lebih baik yang bagus untuk tanah dan pertumbuhan tanaman. Selain mempercepat pertumbuhan tanaman, kantong ini juga melindungi tanaman dari cuaca buruk dan hama, sehingga mengurangi kebutuhan akan pestisida dan perawatan menggunakan bahan kimia lainnya.</p>
