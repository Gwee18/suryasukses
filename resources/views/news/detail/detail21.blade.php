                            <p style="text-align: justify;">Memasuki tahun yang baru, seluruh industri memprediksi tren yang akan berkembang selanjutnya, begitupula dengan industri kemasan plastik. Tren yang berubah dari tahun ke tahun mendorong para pelaku bisnis di bidang kemasan plastik untuk melakukan riset terkait faktor-faktor yang mempengaruhi perubahan minat konsumen, sehingga mereka dapat selalu memenuhi kebutuhan pasar.</p>
                            <p style="text-align: justify;">Prediksi tren kemasan plastik dipengaruhi oleh beberapa faktor seperti pola konsumsi, perubahan gaya hidup masyarakat, dan perubahan kebijakan pemerintah. Selain itu, perkembangan teknologi informasi juga memiliki peran terhadap penggunaan kemasan plastik. Sebagai contoh, saat ini teknologi memudahkan orang berbelanja tanpa keluar rumah melalui situs e-commerce atau online market place. Perilaku berbelanja online ini mempengaruhi konsumsi kemasan plastik karena barang yang akan dikirimkan kepada konsumen dikemas dengan plastik.</p>
                            <p style="text-align: justify;">Saat ini, jenis kemasan plastik yang beredar di masyarakat berupa kemasan plastik kaku atau rigid dan kemasan plastik fleksibel. Kemasan plastik kaku adalah kemasan plastik yang memiliki karakteristik keras, lebih tebal dan tidak mudah diremas. Sedangkan kemasan fleksibel bersifat lebih tipis dan mudah diremas. Tahun ini, kemasan plastik kaku diprediksi masih akan tumbuh, namun juga akan menghadapi tantangan baru dari kemasan fleksibel. Beberapa faktor yang mempengaruhi tren konsumsi plastik rigid adalah sebagai berikut:</p>
                            
                            <p style="text-align: justify;"><strong>Gaya hidup dan lingkungan sosial</strong></p>
                            <p style="text-align: justify;">Pengaruh sosial dan gaya hidup yang dinamis serta cepat mendorong konsumen untuk memilih produk sehari-hari yang dikemas dengan kemasan plastik kaku guna memudahkan mereka untuk menggunakan produk tersebut di tengah kesibukan sehari-hari. Hal ini karena plastik kaku lebih kuat dan memberikan perlindungan terhadap produk.</p>
                            
                            <p style="text-align: justify;"><strong>Plastik kaku sebagai pengganti kemasan tradisional</strong></p>
                            <p style="text-align: justify;">Kemasan tradisional seperti yang terbuat dari kaca dan logam akan tergantikan dengan kemasan plastik kaku. Selain lebih praktis dan ringan, kemasan plastik kaku dinilai lebih hemat biaya sehingga penggunaan plastik kaku akan terus bertahan, bahkan tumbuh walaupun angka pertumbuhannya tidak besar.</p>
                            
                            <p style="text-align: justify;"><strong>Permintaan akan kemasan ramah lingkungan</strong></p>
                            <p style="text-align: justify;">Meskipun kemasan plastik kaku masih akan terus digunakan dan tumbuh, namun jenis plastik tersebut juga menghadapi berbagai tantangan bisnis dengan munculnya beberapa alternatif kemasan jenis lain. Seiring dengan meningkatnya kesadaran masyarakat akan keselamatan lingkungan, permintaan kemasan ramah lingkungapun meningkat. Produsen kemasan plastik menanggapi hal ini dengan memproduksi kemasan yang lebih ramah lingkungan sehingga meminimalisir dampak negatif terhadap alam. Contohnya dengan memproduksi plastik oxo-biodegradable yang lebih tipis dan dapat terdegradasi di alam dalam kurun waktu yang jauh lebih singkat daripada plastik biasa.</p>
                            
                            <p style="text-align: justify;"><strong>Kekhawatiran konsumen tentang limbah makanan dan keamanan pangan</strong></p>
                            <p style="text-align: justify;">Kepedulian masyarakat tentang lingkungan mendorong industri manufaktur untuk lebih peduli tentang pengelolaan limbah. Begitu juga industri pengemasan yang telah memperkenalkan berbagai teknologi pengemasan yang aktif dan cerdas untuk menanggapi hal ini. Sebagai contoh, Suryasukses Group (PT Suryasukses Abadi Prima dan PT Suryasukses Adi Perkasa) yang telah berpengalaman selama lebih dari 30 tahun di bidang food and beverage packaging sangat memperhatikan pengolahan limbah dan keamanan pangan dalam setiap proses produksi yang dijalankan. Dengan menekankan standard tinggi dalam hal food safety, Suryasukses ingin memastikan seluruh proses manufaktur dapat meningkatkan kualitas produk yang dihasilkan sehingga aman untuk digunakan sebagai kemasan makanan atau minuman. Selain itu, Suryasukses juga mengantongi sertifikat ISO 9001 dan FSSC22000 dan menerapkan regulasi standard keamanan internasional.</p>
                            
