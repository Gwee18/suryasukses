                            <p style="text-align: justify;">Penyebaran virus corona atau COVID-19 yang mematikan telah membuat masyarakat dunia resah. Virus yang pertama kali ditemukan di Wuhan China ini awalnya disebarkan melalui sebuah pasar tradisional di mana para pengunjung terekspos langsung dengan hewan yang diperjualbelikan. Kemudian, virus yang berasal dari hewan tersebut selanjutnya menyebar dari orang ke orang ke wilayah yang lebih luas. Virus ini dikabarkan telah membuat lebih dari 6 juta orang terinfeksi dan lebih dari 300 ribu orang di antaranya meninggal dunia. Penyebarannya pun sudah sangat meluas ke seluruh dunia.</p>
